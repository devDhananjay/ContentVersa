#!/usr/bin/env python3
"""
Egress guard — auto-block IPs that pull too much outbound data.

Parses nginx access.log (combined format), sums body_bytes_sent per IP over a
sliding window, and writes nginx geo deny entries. Expires blocks after TTL.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import time
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import unquote

ACCESS_LOG = Path(os.environ.get("EGRESS_ACCESS_LOG", "/var/log/nginx/access.log"))
STATE_FILE = Path(os.environ.get("EGRESS_STATE", "/var/lib/egress-guard/state.json"))
GEO_FILE = Path(os.environ.get("EGRESS_GEO", "/etc/nginx/egress-guard/blocked-ips.geo"))
LOG_FILE = Path(os.environ.get("EGRESS_LOG", "/var/log/egress-guard.log"))
WHITELIST_FILE = Path(
    os.environ.get("EGRESS_WHITELIST", "/etc/nginx/egress-guard/whitelist.txt")
)

# ~200 MB / 10 min ≈ crawler / loop territory. Normal shoppers stay far below.
WINDOW_SECONDS = int(os.environ.get("EGRESS_WINDOW_SECONDS", "600"))
MAX_BYTES = int(os.environ.get("EGRESS_MAX_BYTES", str(200 * 1024 * 1024)))
MAX_REQUESTS = int(os.environ.get("EGRESS_MAX_REQUESTS", "900"))
BLOCK_SECONDS = int(os.environ.get("EGRESS_BLOCK_SECONDS", str(48 * 3600)))

# Combined log: IP - - [22/Oct/2026:11:13:25 +0000] "GET /path HTTP/1.1" 200 47072 "ref" "ua"
LINE_RE = re.compile(
    r'^(?P<ip>\S+) \S+ \S+ \[(?P<ts>[^\]]+)\] "(?P<req>[^"]*)" '
    r'(?P<status>\d+) (?P<bytes>\S+)'
)


def log(msg: str) -> None:
    line = f"{datetime.now(timezone.utc).isoformat()} {msg}"
    print(line, flush=True)
    try:
        LOG_FILE.parent.mkdir(parents=True, exist_ok=True)
        with LOG_FILE.open("a", encoding="utf-8") as f:
            f.write(line + "\n")
    except OSError:
        pass


def load_whitelist() -> set[str]:
    out = {"127.0.0.1", "::1"}
    if WHITELIST_FILE.exists():
        for raw in WHITELIST_FILE.read_text(encoding="utf-8").splitlines():
            raw = raw.split("#", 1)[0].strip()
            if raw:
                out.add(raw)
    return out


def parse_ts(ts: str) -> float | None:
    # 22/Oct/2026:11:13:25 +0000
    try:
        dt = datetime.strptime(ts, "%d/%b/%Y:%H:%M:%S %z")
        return dt.timestamp()
    except ValueError:
        return None


def load_state() -> dict:
    if not STATE_FILE.exists():
        return {"blocked": {}}
    try:
        return json.loads(STATE_FILE.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return {"blocked": {}}


def save_state(state: dict) -> None:
    STATE_FILE.parent.mkdir(parents=True, exist_ok=True)
    tmp = STATE_FILE.with_suffix(".tmp")
    tmp.write_text(json.dumps(state, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    tmp.replace(STATE_FILE)


def write_geo(blocked: dict[str, float]) -> bool:
    """Return True if the deny IP set changed (ignore comment-only churn)."""
    GEO_FILE.parent.mkdir(parents=True, exist_ok=True)
    ip_lines = [f"{ip} 1;" for ip in sorted(blocked)]
    text = (
        "# Auto-generated by egress-guard monitor. Do not edit by hand.\n"
        + "\n".join(ip_lines)
        + ("\n" if ip_lines else "")
    )
    old = GEO_FILE.read_text(encoding="utf-8") if GEO_FILE.exists() else ""
    old_ips = [ln for ln in old.splitlines() if ln.endswith(" 1;")]
    if old_ips == ip_lines and GEO_FILE.exists():
        return False
    tmp = GEO_FILE.with_suffix(".tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(GEO_FILE)
    return True


def nginx_reload() -> None:
    test = subprocess.run(
        ["nginx", "-t"], capture_output=True, text=True
    )
    if test.returncode != 0:
        log(f"nginx -t failed, skip reload: {test.stderr.strip()}")
        return
    subprocess.run(["nginx", "-s", "reload"], check=False)
    log("nginx reloaded")


def scan_log(now: float) -> tuple[dict[str, int], dict[str, int]]:
    bytes_by_ip: dict[str, int] = defaultdict(int)
    reqs_by_ip: dict[str, int] = defaultdict(int)
    if not ACCESS_LOG.exists():
        log(f"missing access log {ACCESS_LOG}")
        return bytes_by_ip, reqs_by_ip

    cutoff = now - WINDOW_SECONDS
    # Read whole current file — rotated daily and truncated after incidents.
    with ACCESS_LOG.open("r", encoding="utf-8", errors="replace") as f:
        for line in f:
            m = LINE_RE.match(line)
            if not m:
                continue
            ts = parse_ts(m.group("ts"))
            if ts is None or ts < cutoff:
                continue
            ip = m.group("ip")
            raw_bytes = m.group("bytes")
            nbytes = 0 if raw_bytes == "-" else int(raw_bytes)
            bytes_by_ip[ip] += nbytes
            reqs_by_ip[ip] += 1
            # Extra signal: nested product from= loops still worth counting hard
            req = m.group("req")
            if "from=" in req and "%2Fproducts%2F" in unquote(req):
                bytes_by_ip[ip] += nbytes  # double-weight loop traffic
    return bytes_by_ip, reqs_by_ip


def main() -> int:
    now = time.time()
    whitelist = load_whitelist()
    state = load_state()
    blocked: dict[str, float] = {
        ip: float(exp)
        for ip, exp in (state.get("blocked") or {}).items()
        if float(exp) > now
    }

    bytes_by_ip, reqs_by_ip = scan_log(now)
    newly: list[str] = []

    for ip, total in bytes_by_ip.items():
        if ip in whitelist:
            continue
        reqs = reqs_by_ip.get(ip, 0)
        if total >= MAX_BYTES or reqs >= MAX_REQUESTS:
            if ip not in blocked:
                newly.append(ip)
            blocked[ip] = now + BLOCK_SECONDS
            log(
                f"BLOCK {ip} bytes={total} reqs={reqs} "
                f"until={datetime.fromtimestamp(blocked[ip], timezone.utc).isoformat()}"
            )

    changed = write_geo(blocked)
    state["blocked"] = blocked
    state["last_run"] = datetime.now(timezone.utc).isoformat()
    state["window_top"] = sorted(
        (
            {"ip": ip, "bytes": b, "reqs": reqs_by_ip.get(ip, 0)}
            for ip, b in bytes_by_ip.items()
        ),
        key=lambda x: x["bytes"],
        reverse=True,
    )[:15]
    save_state(state)

    if changed:
        nginx_reload()
    elif newly:
        log("geo unchanged but new blocks logged (unexpected)")
    else:
        top = state["window_top"][:3]
        summary = ", ".join(
            f"{t['ip']}={t['bytes'] // (1024 * 1024)}MB/{t['reqs']}" for t in top
        ) or "none"
        log(f"ok active_blocks={len(blocked)} top=[{summary}]")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
